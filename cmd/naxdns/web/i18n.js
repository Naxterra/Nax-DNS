// T translates an English string and fills {0}, {1}… with the arguments.
function T(text, ...args) {
  const out = (LANG === 'de' && DE[text]) || text;
  return args.length ? out.replace(/\{(\d)\}/g, (_, i) => args[i]) : out;
}

// TDetail translates the service's status line, which may carry an error.
function TDetail(detail) {
  const prefix = 'Interception failed: ';
  if (detail && detail.startsWith(prefix)) return T(prefix) + detail.slice(prefix.length);
  return T(detail || '');
}
